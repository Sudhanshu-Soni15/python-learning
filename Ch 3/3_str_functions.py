name = "sudhanshu"
print(len(name))  # prints the length of the string
print(name.endswith("shu"))  # checks if the string ends with "shu"
print(name.count("u"))  # counts the occurrences of "u" in the string
print(name.capitalize())  # capitalizes the first letter of the string
print(name.upper())  # converts the string to uppercase
print(name.lower())  # converts the string to lowercase

print(name.find("han"))  # finds the index of the substring "han"
print("Replace:", name.replace("shu", "sh"))  # replaces "shu" with "sh" in the string

print("I am learning \"Python\"")  # prints a string with escaped double quotes
print("I am learning 'Python'")  # prints a string with single quotes
print ("I am loving \npython")  # prints a string with a newline character