a = 10  # this is an integer
b = 22.2  # this is a float
c = "hello world"  # this is a string
d = True  # this is a boolean  
e = None  # this is a NoneType
print ("The type of a is", type(a))  # prints the type of variable a
print ("The type of b is", type(b))  # prints the type of variable b
print ("The type of c is", type(c))  # prints the type of variable c
print ("The type of d is", type(d))  # prints the type of variable d
print ("The type of e is", type(e))  # prints the type of variable e

g = "33.4"
h = float(g)  # converts string g to float and assigns it to h
print ("The type of g is", type(g))  # prints the type of variable g
print ("The type of h is", type(h))  # prints the type of variable h